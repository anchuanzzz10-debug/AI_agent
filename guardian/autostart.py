"""Windows auto-start via Task Scheduler.

Creates a task "Guardian Agent" that starts at your Windows login and runs
`guardian check all --loop N --quiet` in a hidden PowerShell window.

Task settings (chosen for a laptop that monitors 24/7):
  * runs as you, only while you are logged in (needed for Credential Manager)
  * keeps running on battery (Task Scheduler's default would stop it)
  * no 3-day time limit (Task Scheduler's default would kill it)
  * restarts up to 999 times, every minute, if it crashes
  * never starts a second copy
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

TASK_NAME = "Guardian Agent"


class AutostartError(RuntimeError):
    pass


def _ps_quote(value: str) -> str:
    """Single-quoted PowerShell string literal."""
    return "'" + value.replace("'", "''") + "'"


def build_launcher(home: Path, config: Path, interval_min: float, python_exe: str) -> str:
    log = Path(home) / "logs" / "autostart.log"
    return "\r\n".join([
        "# Generated by `guardian autostart install`. Do not edit; reinstall instead.",
        "$ErrorActionPreference = 'Continue'",
        "# The passphrase comes only from Windows Credential Manager, never from a variable.",
        "Remove-Item Env:GUARDIAN_PASSPHRASE -ErrorAction SilentlyContinue",
        f"$env:GUARDIAN_HOME = {_ps_quote(str(home))}",
        f"$env:GUARDIAN_CONFIG = {_ps_quote(str(config))}",
        "$env:PYTHONIOENCODING = 'utf-8'",
        f"New-Item -ItemType Directory -Force -Path {_ps_quote(str(log.parent))} | Out-Null",
        f"& {_ps_quote(python_exe)} -m guardian.cli check all --loop {interval_min:g} --quiet "
        f"*>> {_ps_quote(str(log))}",
        "",
    ])


def build_task_xml(user_id: str, launcher: Path) -> str:
    args = f'-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{launcher}"'
    return f"""<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>Guardian personal agent: website and application monitoring.</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>{escape(user_id)}</UserId>
      <Delay>PT1M</Delay>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{escape(user_id)}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>999</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>powershell.exe</Command>
      <Arguments>{escape(args)}</Arguments>
    </Exec>
  </Actions>
</Task>
"""


def _require_windows() -> None:
    if os.name != "nt":
        raise AutostartError("Auto-start uses Windows Task Scheduler and only works on Windows")


def _current_user() -> str:
    domain = os.environ.get("USERDOMAIN", "")
    user = os.environ.get("USERNAME", "")
    if not user:
        raise AutostartError("Could not determine the Windows user name")
    return f"{domain}\\{user}" if domain else user


def _schtasks(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["schtasks", *args], capture_output=True, text=True)


def install(home: Path, config: Path, interval_min: float, python_exe: str | None = None) -> Path:
    _require_windows()
    system = Path(home) / "system"
    system.mkdir(parents=True, exist_ok=True)
    launcher = system / "guardian-autostart.ps1"
    launcher.write_text(build_launcher(home, config, interval_min, python_exe or sys.executable),
                        encoding="utf-8-sig")
    xml_file = system / "guardian-task.xml"
    xml_file.write_text(build_task_xml(_current_user(), launcher), encoding="utf-16")
    result = _schtasks("/Create", "/TN", TASK_NAME, "/XML", str(xml_file), "/F")
    if result.returncode != 0:
        raise AutostartError(f"Task Scheduler refused the task: {result.stderr.strip() or result.stdout.strip()}")
    return launcher


def start() -> None:
    _require_windows()
    result = _schtasks("/Run", "/TN", TASK_NAME)
    if result.returncode != 0:
        raise AutostartError(result.stderr.strip() or result.stdout.strip())


def stop() -> None:
    _require_windows()
    _schtasks("/End", "/TN", TASK_NAME)


def remove() -> bool:
    _require_windows()
    _schtasks("/End", "/TN", TASK_NAME)
    return _schtasks("/Delete", "/TN", TASK_NAME, "/F").returncode == 0


def status() -> str:
    _require_windows()
    result = _schtasks("/Query", "/TN", TASK_NAME, "/V", "/FO", "LIST")
    if result.returncode != 0:
        return "Not installed"
    wanted = ("Status:", "Last Run Time:", "Last Result:", "Next Run Time:")
    lines = [l.strip() for l in result.stdout.splitlines() if l.strip().startswith(wanted)]
    return "\n".join(lines) or result.stdout.strip()
